#!/usr/bin/env python3
"""Render the README infographics from readme.html with headless Chrome.

Requires google-chrome (or CHROME=<path>), Pillow and FontTools. Output: docs/images/*.png
"""
import importlib.util
import json
import os
import subprocess
import tempfile
from pathlib import Path

from PIL import Image, ImageChops

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
PANELS = ["dock", "anatomy", "colors", "pacing", "zoom", "cooldown", "states"]
BACKGROUND = (11, 11, 14)

spec = importlib.util.spec_from_file_location("font", ROOT / "scripts/generate-meter-font.py")
font = importlib.util.module_from_spec(spec)
spec.loader.exec_module(font)
(HERE / "marks.js").write_text("// Generated by docs/images/src/render.py from scripts/generate-meter-font.py.\n"
                               "const MARKS = " + json.dumps([chr(c) for c in font.MARKS]) + ";\n")

chrome = os.environ.get("CHROME", "google-chrome")
for panel in PANELS:
    with tempfile.TemporaryDirectory() as profile:
        raw = Path(profile) / "shot.png"
        subprocess.run([chrome, "--headless=new", "--disable-gpu", "--hide-scrollbars", "--allow-file-access-from-files",
                        f"--user-data-dir={profile}", "--force-device-scale-factor=2", "--window-size=1248,1100",
                        "--virtual-time-budget=2000", f"--screenshot={raw}", (HERE / "readme.html").as_uri() + "#" + panel],
                       check=True, capture_output=True)
        image = Image.open(raw).convert("RGB")
    # Crop to the panel: trim the page background, keep a small margin.
    box = ImageChops.difference(image, Image.new("RGB", image.size, BACKGROUND)).getbbox()
    out = ROOT / "docs/images" / f"{panel}.png"
    image.crop(box).save(out, optimize=True)
    print(out.relative_to(ROOT), image.crop(box).size)
